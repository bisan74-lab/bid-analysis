// 경상남도 산하 시/군(기초자치단체) 발주처는 관내 제한(그 시/군 등록 업체만 참여 가능) 대상으로 추정되어
// 부산 소재 회사인 우리는 입찰 자격이 없다. 도(광역자치단체) 단위 발주처는 관내 제한이 없으므로 제외하지 않는다.
//
// 판정 방식: "발주처명에 경남 시/군명이 들어있으면 기본적으로 제외"하고, 국가/도(道) 단위로 확인되는
// 기관(한국OO공사 등 공기업, 경상남도 직속 사업소, 도교육청/소방서, 군부대, 중앙정부 부처·지방청,
// 국립대학교)만 예외로 유지한다(화이트리스트). 반대로 "경남/경상남도 뒤에 시/군명이 오는 경우만" 같은
// 좁은 블랙리스트 방식은 "경상남도진주교육지원청", 개별 학교(진주중학교 등)처럼 다른 형태로 표기된
// 시/군 소속 기관을 놓치는 문제가 있어 (2026-07-05 확인) 이 방식으로 변경함.
const GYEONGNAM_CITY_COUNTIES = [
  '창원', '진주', '통영', '사천', '김해', '밀양', '거제', '양산', // 8 시
  '의령', '함안', '창녕', '고성', '남해', '하동', '산청', '함양', '거창', '합천', // 10 군
];

// 시/군명이 발주처명에 들어있어도 실제로는 국가·도 단위(광역) 기관이라 관내 제한 대상이 아닌 경우.
// (예: "한국농어촌공사 경남지역본부 진주.산청지사", "경상남도 도로관리사업소 진주지소",
//      "경상남도교육청 경상남도진주교육지원청", "경상남도 진주소방서")
const PROVINCIAL_OR_NATIONAL_WHITELIST = [
  /^경상남도$/,
  /도로관리사업소|항만관리사업소/,
  /교육청|교육지원청/,
  /소방서|소방본부/,
  /한국도로공사|한국농어촌공사|한국수자원공사|한국전력공사|한국토지주택공사|한국공항공사|한국가스공사|한국지역난방공사|한국석유공사|한국엘피지사업관리원|한국조폐공사|한국철도공사|코레일/,
  /^(국방부|국군|육군|해군|공군)|군수지원사령부|사령부$|부대$|^제\d/, // "남해군"의 "해군"처럼 우연히 겹치지 않도록 문자열 시작 위치로 한정
  /^국토교통부|^해양수산부|^문화체육관광부|^환경부|^산림청|^대검찰청|^법무부|^경찰청|지방국토관리청|지방해양수산청|지방조달청|해양경찰청/,
  /국립.*대학교|경상국립대학교/,
  /주식회사/, // 민간 사기업(발주처가 아니라 시설 운영사 등)은 관내 제한 대상이 아님
];

function isGyeongnamCityRestricted(발주처) {
  if (!발주처) return false;
  const mentionsCity = GYEONGNAM_CITY_COUNTIES.some(city => 발주처.includes(city));
  if (!mentionsCity) return false;
  const isWhitelisted = PROVINCIAL_OR_NATIONAL_WHITELIST.some(re => re.test(발주처));
  return !isWhitelisted;
}

module.exports = { GYEONGNAM_CITY_COUNTIES, isGyeongnamCityRestricted };
